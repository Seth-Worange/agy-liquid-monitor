function translateMonitor(language, key, ...values) {
  if (language === 'en' && Object.hasOwn(monitorEnglish, key)) {
    const english = monitorEnglish[key];
    key = Array.isArray(english) ? english[values[0] === 1 ? 0 : 1] : english;
  }
  return values.length ? key.replace(/\{(\d+)\}/g, (_, index) => values[index] ?? '') : key;
}

function localizeMonitorMarkup(root, t) {
  for (const attribute of ['data-i18n', 'data-i18n-label', 'data-i18n-title']) {
    for (const node of root.querySelectorAll(`[${attribute}]`)) {
      const text = t(node.getAttribute(attribute));
      if (attribute === 'data-i18n') {
        if (node.textContent !== text) node.textContent = text;
      } else {
        node.setAttribute(attribute === 'data-i18n-label' ? 'aria-label' : 'title', text);
      }
    }
  }
}
